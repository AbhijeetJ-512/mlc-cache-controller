`timescale 1ns/1ps

// Tier-1 test of plru_tree at the other associativities the project needs: 2 ways (the PM-05 /
// PM-08 lower bound) and 8 ways (L3). tb_plru.sv already covers 4 ways in depth.
//
// For each associativity: every single access, and every ordered pair of accesses, from the reset
// state, with the expected victim taken from a table. The tables come from
// scripts/gen_plru_tables.py, which models tree-PLRU by recursing on way ranges - a different
// formulation from the RTL's iterative bit walk - and which first asserts a few results worked
// out by hand (2-way: way0 then victim 1; 4-way: the Phase 0 worked example; 8-way: touching
// 0..7 in order leaves way 0 as the victim).
//
// Two groups of checks do not come from the tables. At 8 ways every way is steered to be the
// victim from the definition of the policy (the tables only ever reach even ways), and the set
// ports are exercised with different set numbers, since every other test ties them to set 0.
module tb_plru_ways;

  logic clk = 1'b0;
  always #5 clk = ~clk;
  logic rst_n;
  int errors = 0;

  logic [0:0] v2;  logic acc2;  logic [0:0] way2;
  logic [2:0] v8;  logic acc8;  logic [2:0] way8;

  plru_tree #(.WAYS(2), .SETS(4)) d2 (.clk(clk), .rst_n(rst_n), .set_index(2'd0), .victim_way(v2),
                                      .access_valid(acc2), .access_set(2'd0), .access_way(way2));
  // The 8-way instance's set ports are variables so the per-set tests at the end can use them; every
  // other test leaves both at set 0.
  logic [1:0] sel8 = 2'd0, aset8 = 2'd0;
  plru_tree #(.WAYS(8), .SETS(4)) d8 (.clk(clk), .rst_n(rst_n), .set_index(sel8), .victim_way(v8),
                                      .access_valid(acc8), .access_set(aset8), .access_way(way8));

  int exp2_len1 [0:1];
  int exp2_len2 [0:3];
  int exp8_len1 [0:7];
  int exp8_len2 [0:63];

  task automatic check(input logic cond, input string msg);
    if (cond) $display("PASS: %s", msg);
    else begin
      $display("FAIL: %s", msg);
      errors++;
    end
  endtask

  task automatic do_reset();
    rst_n <= 1'b0;
    repeat (2) @(posedge clk);
    rst_n <= 1'b1;
    @(posedge clk);
  endtask

  task automatic touch2(input int w);
    acc2 <= 1'b1; way2 <= w[0:0];
    @(posedge clk);
    acc2 <= 1'b0;
    #1;
  endtask

  task automatic touch8(input int w);
    acc8 <= 1'b1; way8 <= w[2:0];
    @(posedge clk);
    acc8 <= 1'b0;
    #1;
  endtask

  initial begin
    acc2 = 1'b0; way2 = '0; acc8 = 1'b0; way8 = '0;

    // ---- expected-victim tables, generated by scripts/gen_plru_tables.py ----
    exp2_len1[0] = 1;
    exp2_len1[1] = 0;
    exp2_len2[0] = 1;
    exp2_len2[1] = 0;
    exp2_len2[2] = 1;
    exp2_len2[3] = 0;
    exp8_len1[0] = 4;
    exp8_len1[1] = 4;
    exp8_len1[2] = 4;
    exp8_len1[3] = 4;
    exp8_len1[4] = 0;
    exp8_len1[5] = 0;
    exp8_len1[6] = 0;
    exp8_len1[7] = 0;
    exp8_len2[0] = 4;  exp8_len2[1] = 4;  exp8_len2[2] = 4;  exp8_len2[3] = 4;
    exp8_len2[4] = 2;  exp8_len2[5] = 2;  exp8_len2[6] = 2;  exp8_len2[7] = 2;
    exp8_len2[8] = 4;  exp8_len2[9] = 4;  exp8_len2[10] = 4; exp8_len2[11] = 4;
    exp8_len2[12] = 2; exp8_len2[13] = 2; exp8_len2[14] = 2; exp8_len2[15] = 2;
    exp8_len2[16] = 4; exp8_len2[17] = 4; exp8_len2[18] = 4; exp8_len2[19] = 4;
    exp8_len2[20] = 0; exp8_len2[21] = 0; exp8_len2[22] = 0; exp8_len2[23] = 0;
    exp8_len2[24] = 4; exp8_len2[25] = 4; exp8_len2[26] = 4; exp8_len2[27] = 4;
    exp8_len2[28] = 0; exp8_len2[29] = 0; exp8_len2[30] = 0; exp8_len2[31] = 0;
    exp8_len2[32] = 6; exp8_len2[33] = 6; exp8_len2[34] = 6; exp8_len2[35] = 6;
    exp8_len2[36] = 0; exp8_len2[37] = 0; exp8_len2[38] = 0; exp8_len2[39] = 0;
    exp8_len2[40] = 6; exp8_len2[41] = 6; exp8_len2[42] = 6; exp8_len2[43] = 6;
    exp8_len2[44] = 0; exp8_len2[45] = 0; exp8_len2[46] = 0; exp8_len2[47] = 0;
    exp8_len2[48] = 4; exp8_len2[49] = 4; exp8_len2[50] = 4; exp8_len2[51] = 4;
    exp8_len2[52] = 0; exp8_len2[53] = 0; exp8_len2[54] = 0; exp8_len2[55] = 0;
    exp8_len2[56] = 4; exp8_len2[57] = 4; exp8_len2[58] = 4; exp8_len2[59] = 4;
    exp8_len2[60] = 0; exp8_len2[61] = 0; exp8_len2[62] = 0; exp8_len2[63] = 0;

    rst_n = 1'b0;
    repeat (2) @(posedge clk);
    rst_n = 1'b1;
    @(posedge clk); #1;

    check(v2 === 1'b0, "2-way: reset victim is way 0");
    check(v8 === 3'd0, "8-way: reset victim is way 0");

    // ---- 2 ways: exhaustive length 1 and 2 ----
    for (int a = 0; a < 2; a++) begin
      do_reset();
      touch2(a);
      check(v2 === exp2_len1[a][0:0], $sformatf("2-way [%0d]: victim matches the table", a));
    end
    for (int a = 0; a < 2; a++)
      for (int b = 0; b < 2; b++) begin
        do_reset();
        touch2(a); touch2(b);
        check(v2 === exp2_len2[a*2 + b][0:0], $sformatf("2-way [%0d,%0d]: victim matches the table", a, b));
      end

    // ---- 8 ways: exhaustive length 1 and 2 ----
    for (int a = 0; a < 8; a++) begin
      do_reset();
      touch8(a);
      check(v8 === exp8_len1[a][2:0], $sformatf("8-way [%0d]: victim matches the table", a));
    end
    for (int a = 0; a < 8; a++)
      for (int b = 0; b < 8; b++) begin
        do_reset();
        touch8(a); touch8(b);
        check(v8 === exp8_len2[a*8 + b][2:0], $sformatf("8-way [%0d,%0d]: victim matches the table", a, b));
      end

    // ---- 8 ways: a full fill, then the oldest line is the victim ----
    do_reset();
    for (int w = 0; w < 8; w++) touch8(w);
    check(v8 === 3'd0, "8-way: after touching ways 0..7 in order, way 0 is the victim");
    touch8(0);
    check(v8 === 3'd4, "8-way: touching way 0 again moves the victim to the other half (way 4)");

    // ---- 8 ways: every way can become the victim (the leaf level of the tree) ----
    // The tables above only reach even victims (a pair of accesses never leaves a leaf bit pointing
    // at an odd way), so a tree that dropped its leaf level, or could never choose ways 1, 3, 5 or 7,
    // passed them. Touching w's sibling, then the nearest way across the next level, then the way
    // across the root, steers every node on w's path to w - from the definition, not from a table.
    for (int w = 0; w < 8; w++) begin
      do_reset();
      touch8(w ^ 1); touch8(w ^ 2); touch8(w ^ 4);
      check(v8 === w[2:0], $sformatf("8-way: touching %0d, %0d, %0d makes way %0d the victim", w ^ 1, w ^ 2, w ^ 4, w));
    end

    // ---- 8 ways: each set keeps its own tree, and an access updates the set it names ----
    // The accesses use ways in the left half (0..3): from the reset state their victim is not way 0,
    // so they cannot be mistaken for an untouched set. Each read of a set follows a #1 so the
    // combinational victim has settled on the newly selected set.
    do_reset();
    aset8 = 2'd2; touch8(1);                      // set 2 only: victim moves to way 4
    sel8 = 2'd2; #1;
    check(v8 === exp8_len1[1][2:0], "per-set: the accessed set's victim follows the access");
    for (int s = 0; s < 4; s++) begin
      sel8 = s[1:0]; #1;
      if (s != 2) check(v8 === 3'd0, $sformatf("per-set: set %0d is untouched by an access to set 2", s));
    end
    aset8 = 2'd3; sel8 = 2'd1;                    // set 3 is updated while set 1 is being read
    touch8(1); touch8(4);
    check(v8 === 3'd0, "per-set: the set being read does not follow accesses to another set");
    sel8 = 2'd3; #1;
    check(v8 === exp8_len2[1*8 + 4][2:0], "per-set: set 3 holds its own tree");
    sel8 = 2'd2; #1;
    check(v8 === exp8_len1[1][2:0], "per-set: set 2 kept its tree through the accesses to set 3");
    sel8 = 2'd0; #1;
    check(v8 === 3'd0, "per-set: set 0 was never touched");
    aset8 = 2'd0; sel8 = 2'd0;

    if (errors == 0) begin
      $display("** ALL TESTS PASSED **");
      $finish;
    end else begin
      $display("** %0d TEST(S) FAILED **", errors);
      $fatal(1);
    end
  end

  initial begin
    #1000000;
    $display("FAIL: simulation watchdog timeout");
    errors++;
    $fatal(1);
  end

endmodule
