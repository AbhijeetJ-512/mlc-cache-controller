#!/usr/bin/env python3
"""Turn build/reports/<point>/{run,stat}.txt into build/reports/summary.md (Phase 7, D-037).

Every figure in the table is read from a checked-in report file; nothing is computed except the flip-flop count, which
adds up the flip-flop cell lines of stat.txt. A point with no run.txt is listed as NOT YET MEASURED.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import synth_run  # the point table lives there

REPORTS = synth_run.REPORTS
ORDER = [("default", "Default configuration"), ("sweep", "Capacity / associativity sweep"),
         ("l3-default", "Default L3 (256 KiB, 8-way)"), ("abc-compare", "ABC mode comparison (L1-D)")]


def read_kv(path):
    kv = {}
    for line in path.read_text().splitlines():
        k, _, v = line.partition(": ")
        kv[k] = v
    return kv


_AREAS = {}


def cell_area(name):
    """Area of one library cell, read from the liberty (first `area :` line after its `cell (...)` line)."""
    if not _AREAS:
        current = None
        for line in synth_run.LIB.read_text().splitlines():
            m = re.match(r'\s+cell \("(sky130_fd_sc_hd__\w+)"\)', line)
            if m:
                current = m.group(1)
                continue
            m = re.match(r"\s+area : ([0-9.]+);", line)
            if m and current and current not in _AREAS:
                _AREAS[current] = float(m.group(1))
    return _AREAS[name]


def read_stat(path):
    text = path.read_text()
    area = re.findall(r"Chip area for module '[^']*': ([0-9.]+)", text)
    cells = re.findall(r"Number of cells:\s+(\d+)", text)
    flop_lines = re.findall(r"(sky130_fd_sc_hd__(?:df|sdf|edf)\w*)\s+(\d+)", text)
    flops = sum(int(n) for _, n in flop_lines)
    flop_area = sum(int(n) * cell_area(c) for c, n in flop_lines)
    return float(area[-1]), int(cells[0]), flops, flop_area


def stored_bits(spec):
    """Bits of state the architecture stores: data, tag and valid (plus dirty and PLRU for L2/L3). None for a unit with no arrays."""
    top, p = spec["top"], dict(kv.split("=") for kv in spec["params"].split())
    if top in ("l1_icache_ctrl", "l1_dcache_ctrl"):
        cap, line = spec["pkg"].get("L1_CAPACITY_B", 4096), 32
        sets = cap // line
        return sets * (line * 8 + (32 - sets.bit_length() + 1 - 5) + 1)
    if top in ("l2_cache_ctrl", "l3_cache_ctrl"):
        l3 = top == "l3_cache_ctrl"
        cap = int(p.get("CAPACITY_B", 262144 if l3 else 32768))
        ways = int(p.get("WAYS", 8 if l3 else 4))
        line = 64 if l3 else 32
        lines = cap // line
        sets = lines // ways
        tag = 32 - (sets.bit_length() - 1) - (line.bit_length() - 1)
        return lines * (line * 8 + tag + 2) + sets * (ways - 1)
    return None


def row(name):
    spec = synth_run.POINTS[name]
    cfg = spec["params"] or "defaults"
    if spec["pkg"]:
        cfg = ", ".join("%s=%d" % kv for kv in spec["pkg"].items())
    run = REPORTS / name / "run.txt"
    if not run.exists():
        cols = [name, spec["top"], cfg, "NOT YET MEASURED", "", "", "", "", "", "", "", "", ""]
        return "| " + " | ".join(cols) + " |"
    kv = read_kv(run)
    status = kv["status"] if kv["reason"] == "-" else "%s (%s)" % (kv["status"], kv["reason"])
    area = cells = flops = bits = other = share = ""
    stat = REPORTS / name / "stat.txt"
    if kv["status"] == "ok" and stat.exists():
        a, c, f, fa = read_stat(stat)
        area, cells, flops = "{:,.0f}".format(a), "{:,}".format(c), "{:,}".format(f)
        share = "%.0f%%" % (100 * fa / a) if f else ""
        b = stored_bits(spec)
        if b is not None:
            bits, other = "{:,}".format(b), "{:,}".format(f - b)
    peak_gib = "%.2f" % (int(kv["peak_rss_kib"]) / 1048576)
    cols = [name, spec["top"], cfg, status, kv["abc"], area, cells, flops, share, bits, other, kv["wall_seconds"], peak_gib]
    return "| " + " | ".join(cols) + " |"


def main():
    out = ["# Synthesis results (Yosys 0.33, Sky130HD typical corner)", "",
           "Generated by `scripts/synth_summary.py` from the `run.txt` and `stat.txt` of each point. Area is the Yosys `stat -liberty`",
           "cell area in square micrometres of the mapped, flattened module. Wall time and peak memory are from the development",
           "machine and are shown because the flow's feasibility is part of the result (OQ-4, R5).",
           "'Stored bits' is what the architecture keeps in arrays (data, tag, valid, and dirty and PLRU state for L2 and L3), computed from",
           "the parameters; 'other flip-flops' is the measured flip-flop count minus that, i.e. the control and datapath registers. A",
           "negative or large value would mean an array was optimised away or mis-sized. 'Flip-flop area' is the share of the area that is",
           "flip-flop cells (areas from the liberty); the rest is the logic around them.", ""]
    for group, title in ORDER:
        names = [n for n, s in synth_run.POINTS.items() if group in s["groups"]]
        out += ["## " + title, "",
                "| point | module | parameters | status | ABC | area (um^2) | cells | flip-flops | flip-flop area | stored bits | other flip-flops | wall (s) | peak memory (GiB) |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        out += [row(n) for n in names]
        out.append("")
    text = "\n".join(out)
    (REPORTS / "summary.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
